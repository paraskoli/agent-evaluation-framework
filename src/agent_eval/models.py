"""Data models for agent executions, trajectories, and benchmark evaluations."""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ToolCall(BaseModel):
    """Record of a single tool invocation by the agent."""
    name: str = Field(..., description="Name of the invoked tool")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Arguments passed to the tool")
    output: str = Field(default="", description="Output or return string from the tool execution")
    latency_ms: float = Field(default=0.0, description="Execution time in milliseconds")
    success: bool = Field(default=True, description="Whether the tool executed without unhandled errors")
    error: Optional[str] = Field(default=None, description="Error message if execution failed")


class TrajectoryStep(BaseModel):
    """A single reasoning and acting step in the agent's multi-step execution."""
    step_number: int = Field(..., description="1-indexed sequence number of the step")
    thought: str = Field(default="", description="Chain-of-thought or internal reasoning")
    tool_calls: List[ToolCall] = Field(default_factory=list, description="Tools called during this step")
    observation: str = Field(default="", description="Consolidated observation returned to model")
    step_latency_ms: float = Field(default=0.0, description="Total step duration in ms")


class AgentTrajectory(BaseModel):
    """Full trajectory trace of an agent completing a task."""
    task_id: Optional[str] = Field(default=None, description="Identifier of the task or benchmark case")
    query: str = Field(..., description="Initial input prompt or task given to the agent")
    steps: List[TrajectoryStep] = Field(default_factory=list, description="Sequence of trajectory steps")
    final_answer: str = Field(default="", description="Agent's final response to the user")
    completed: bool = Field(default=True, description="Whether the task concluded naturally")
    error: Optional[str] = Field(default=None, description="Unrecoverable error if any")
    total_steps: int = Field(default=0, description="Total number of reasoning/acting steps taken")
    total_latency_ms: float = Field(default=0.0, description="Total wall-clock duration in ms")
    prompt_tokens: int = Field(default=0, description="Prompt tokens consumed")
    completion_tokens: int = Field(default=0, description="Completion tokens generated")
    estimated_cost_usd: float = Field(default=0.0, description="Estimated total API cost in USD")


class BenchmarkCase(BaseModel):
    """Golden dataset item representing a benchmark challenge."""
    id: str = Field(..., description="Unique case identifier (e.g. tc_001)")
    query: str = Field(..., description="Input user prompt to feed to the agent")
    expected_tools: List[str] = Field(
        default_factory=list,
        description="Tools expected to be called during an optimal solve"
    )
    optimal_steps: int = Field(
        default=1,
        description="Minimum reasonable steps expected to solve this task"
    )
    ground_truth_answer: Optional[str] = Field(
        default=None,
        description="Canonical ground truth answer for deterministic checking"
    )
    rubric: Optional[str] = Field(
        default=None,
        description="Grading rubric for LLM-as-a-judge evaluation"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary metadata such as category, difficulty, ticker, etc."
    )


class MetricScore(BaseModel):
    """Individual metric score result."""
    name: str = Field(..., description="Metric name, e.g. tool_precision, step_efficiency")
    score: float = Field(..., description="Normalized score value (usually 0.0 - 1.0)")
    passed: bool = Field(..., description="Whether score meets the defined pass threshold")
    threshold: float = Field(default=0.8, description="Pass/fail threshold for this metric")
    details: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic context or explanation")


class EvaluationResult(BaseModel):
    """Complete evaluation report for a single benchmark test case."""
    case_id: str = Field(..., description="Benchmark case ID")
    passed: bool = Field(..., description="True if all critical metrics met their thresholds")
    overall_score: float = Field(..., description="Weighted average of all metric scores (0.0 - 1.0)")
    metric_scores: List[MetricScore] = Field(default_factory=list, description="Individual metric breakdowns")
    trajectory: AgentTrajectory = Field(..., description="The trajectory generated by the agent")
    judge_critique: Optional[str] = Field(default=None, description="Reasoning provided by the judge")
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Timestamp of evaluation"
    )


class BenchmarkSummary(BaseModel):
    """Aggregated evaluation metrics across an entire test suite."""
    suite_name: str = Field(default="Agent Benchmark Suite")
    model_name: str = Field(default="unknown")
    total_cases: int = Field(default=0)
    passed_cases: int = Field(default=0)
    pass_rate: float = Field(default=0.0, description="Percentage of test cases passing all thresholds")
    mean_overall_score: float = Field(default=0.0)
    avg_step_efficiency: float = Field(default=0.0)
    avg_tool_precision: float = Field(default=0.0)
    avg_tool_recall: float = Field(default=0.0)
    avg_latency_ms: float = Field(default=0.0)
    total_cost_usd: float = Field(default=0.0)
    results: List[EvaluationResult] = Field(default_factory=list)
